/**
 * Burtek Mutfak — build script
 * Reads data/products.json (edited via Pages CMS) and generates data/products.js
 * which the static HTML loads as a synchronous script.
 *
 * Runs automatically on Vercel deploy via the "vercel-build" npm script.
 * Run locally with: node build-products.js
 */

const fs = require("fs");
const path = require("path");

const SRC = path.join(__dirname, "data", "products.json");
const OUT = path.join(__dirname, "data", "products.js");

if (!fs.existsSync(SRC)) {
  console.error("[build-products] data/products.json not found");
  process.exit(1);
}

const raw = fs.readFileSync(SRC, "utf8");
let data;
try {
  data = JSON.parse(raw);
} catch (e) {
  console.error("[build-products] data/products.json is not valid JSON:", e.message);
  process.exit(1);
}

const products = Array.isArray(data.products) ? data.products : [];
const categories = Array.isArray(data.categories) ? data.categories : [];

// Recalculate "all" count to keep it in sync with products length
const cats = categories.map((c) =>
  c.id === "all" ? { ...c, count: products.length } : c
);

const banner = `/* Burtek Mutfak — Auto-generated from data/products.json
   Do not edit this file directly. Use the Pages CMS or edit products.json
   and run \`node build-products.js\` to regenerate.
   Generated: ${new Date().toISOString()} */\n\n`;

const js =
  banner +
  `window.BURTEK_PRODUCTS = ${JSON.stringify(products, null, 2)};\n\n` +
  `window.BURTEK_CATEGORIES = ${JSON.stringify(cats, null, 2)};\n`;

fs.writeFileSync(OUT, js, "utf8");
console.log(
  `[build-products] wrote ${OUT}: ${products.length} products, ${cats.length} categories`
);
